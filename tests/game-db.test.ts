import test from "node:test";
import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { PGlite } from "@electric-sql/pglite";

test("live game keeps answers private, enforces timers and records scores atomically", async () => {
  const db = new PGlite();
  try {
    await db.exec(`create role anon; create role authenticated; create role service_role; create schema auth;
      create table auth.users (id uuid primary key, raw_user_meta_data jsonb);
      create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid $$;
      grant usage on schema auth to authenticated, anon; grant execute on function auth.uid() to authenticated, anon;`);
    for (const path of ["20261124000000_profiles.sql", "20261127000000_quizzes.sql", "20261128000000_lobby.sql", "20261129000000_live_quiz.sql"]) await db.exec(await readFile(`supabase/migrations/${path}`, "utf8"));
    const teacher = "11111111-1111-4111-8111-111111111111", stranger = "22222222-2222-4222-8222-222222222222";
    await db.query("insert into auth.users values ($1, '{\"display_name\":\"Teacher\"}'), ($2, '{\"display_name\":\"Other\"}')", [teacher, stranger]);
    await db.exec(`set role authenticated; select set_config('request.jwt.claim.sub', '${teacher}', false);`);
    const payload = { title: "Science", description: "", subject: "", grade: "", topic: "", coverUrl: "", status: "published", questions: [
      { text: "First?", explanation: "First explanation SECRET", timeLimit: 30, points: 100, correctIndex: 0, options: ["A", "B", "C", "D"] },
      { text: "FUTURE QUESTION SECRET", explanation: "Future explanation SECRET", timeLimit: 30, points: 200, correctIndex: 1, options: ["E", "F", "G", "H"] }
    ] };
    const saved = (await db.query<{ result: { id: string; updatedAt: string } }>("select public.save_teacher_quiz(null,null,$1::jsonb) result", [JSON.stringify(payload)])).rows[0].result;
    const game = (await db.query<{ result: { id: string } }>("select public.create_teacher_lobby($1) result", [saved.id])).rows[0].result;
    type Command = { ok?: boolean; error?: string };
    const command = (cmd: string) => db.query<{ result: Command }>("select public.teacher_game_command($1,$2) result", [game.id, cmd]);
    assert.equal((await command("start")).rows[0].result.error, "no_players");
    const host = (await db.query<{ result: { code: string } }>("select public.teacher_lobby_state($1) result", [game.id])).rows[0].result;
    const pin = host.code, token = "a".repeat(64), otherToken = "c".repeat(64), secondToken = "d".repeat(64), rate = "b".repeat(64);
    await db.exec("set role service_role");
    assert.equal((await db.query<{ result: Command }>("select public.join_guest_lobby($1,'Alex',$2,$3) result", [pin, token, rate])).rows[0].result.ok, true);
    assert.equal((await db.query<{ result: Command }>("select public.join_guest_lobby($1,'Jamie',$2,$3) result", [pin, secondToken, rate])).rows[0].result.ok, true);
    await db.exec(`set role authenticated; select set_config('request.jwt.claim.sub', '${stranger}', false);`);
    assert.equal((await command("start")).rows[0].result.error, "not_found");
    await db.exec(`select set_config('request.jwt.claim.sub', '${teacher}', false);`);
    assert.equal((await command("start")).rows[0].result.ok, true);
    await assert.rejects(db.query("select * from public.game_session_questions"));
    await assert.rejects(db.query("select public.game_view_internal($1,null)", [game.id]));
    await assert.rejects(db.query("select public.submit_guest_answer($1,$2,0,0)", [pin, token]));
    await assert.rejects(db.query("select public.save_teacher_quiz($1,$2,$3::jsonb)", [saved.id, saved.updatedAt, JSON.stringify(payload)]));
    await db.exec("set role service_role");
    const view = () => db.query<{ result: Record<string, unknown> }>("select public.guest_lobby_state($1,$2) result", [pin, token]);
    assert.equal((await db.query<{ result: unknown }>("select public.guest_lobby_state($1,$2) result", [pin, otherToken])).rows[0].result, null);
    assert.equal((await db.query<{ result: Command }>("select public.join_guest_lobby($1,'Alex',$2,$3) result", [pin, token, rate])).rows[0].result.ok, true, "existing guest may reconnect after start");
    assert.equal((await db.query<{ result: Command }>("select public.join_guest_lobby($1,'New student',$2,$3) result", [pin, otherToken, rate])).rows[0].result.error, "unavailable", "new players cannot join a started game");
    const initial = (await view()).rows[0].result;
    assert.equal(initial.status, "question");
    assert.doesNotMatch(JSON.stringify(initial), /correctIndex|explanation|FUTURE QUESTION SECRET|First explanation SECRET/);
    const submit = (index: number, option: number) => db.query<{ result: Command }>("select public.submit_guest_answer($1,$2,$3,$4) result", [pin, token, index, option]);
    assert.equal((await submit(1, 1)).rows[0].result.error, "closed", "stale question must be rejected");
    assert.equal((await submit(0, 0)).rows[0].result.ok, true);
    assert.equal((await db.query<{ result: Command }>("select public.submit_guest_answer($1,$2,0,2) result", [pin, secondToken])).rows[0].result.ok, true);
    assert.equal((await submit(0, 0)).rows[0].result.error, "already_answered");
    const answered = (await view()).rows[0].result;
    assert.equal(answered.score, 0, "current score is hidden until reveal");
    assert.doesNotMatch(JSON.stringify(answered), /correctIndex|explanation|FUTURE QUESTION SECRET/);
    await db.exec(`set role authenticated; select set_config('request.jwt.claim.sub', '${teacher}', false);`);
    assert.equal((await command("reveal")).rows[0].result.ok, true);
    await db.exec("set role service_role");
    const reveal = (await view()).rows[0].result;
    assert.equal((reveal.question as { correctIndex: number }).correctIndex, 0);
    assert.equal(reveal.score, 100);
    assert.equal((await submit(0, 0)).rows[0].result.error, "closed");
    await db.exec(`set role authenticated; select set_config('request.jwt.claim.sub', '${teacher}', false);`);
    assert.equal((await command("next")).rows[0].result.ok, true);
    await db.exec("reset role");
    await db.query("update public.game_sessions set question_closes_at = clock_timestamp() - interval '1 second' where id = $1", [game.id]);
    await db.exec("set role service_role");
    assert.equal((await submit(1, 1)).rows[0].result.error, "closed", "server rejects after timer");
    const expiredQuestion = (await view()).rows[0].result;
    assert.equal((expiredQuestion.question as { canAnswer: boolean }).canAnswer, false);
    assert.doesNotMatch(JSON.stringify(expiredQuestion), /correctIndex|Future explanation SECRET/);
    await db.exec(`set role authenticated; select set_config('request.jwt.claim.sub', '${teacher}', false);`);
    assert.equal((await command("reveal")).rows[0].result.ok, true);
    assert.equal((await command("next")).rows[0].result.ok, true);
    assert.equal((await command("next")).rows[0].result.error, "invalid_state");
    await db.exec("set role service_role");
    const finished = (await view()).rows[0].result;
    assert.equal(finished.status, "finished");
    assert.equal((finished.leaderboard as Array<{ score: number; correct: number; unanswered: number }>)[0].score, 100);
    assert.equal((finished.leaderboard as Array<{ correct: number }>)[0].correct, 1);
    assert.equal((finished.leaderboard as Array<{ unanswered: number }>)[0].unanswered, 1);
    assert.equal((finished.leaderboard as Array<{ score: number; incorrect: number }>)[1].score, 0);
    assert.equal((finished.leaderboard as Array<{ score: number; incorrect: number }>)[1].incorrect, 1);
    await db.exec("reset role");
    assert.equal((await db.query("select * from public.game_results where session_id = $1", [game.id])).rows.length, 2);
    await db.exec(`set role authenticated; select set_config('request.jwt.claim.sub', '${teacher}', false);`);
    assert.equal((await db.query<{ result: boolean }>("select public.delete_teacher_quiz($1) result", [saved.id])).rows[0].result, true);
    assert.equal((await db.query<{ result: { status: string; title: string } }>("select public.teacher_lobby_state($1) result", [game.id])).rows[0].result.status, "finished", "results survive quiz deletion");
  } finally { await db.close(); }
});
